import './build.mjs';
import fs from 'node:fs';
import {gunzipSync,gzipSync} from 'node:zlib';
let worker=fs.readFileSync('dist/server/index.js','utf8');
const embedded=fs.readFileSync('data/visual-index.json.gz').toString('base64');
worker=worker.replace(JSON.stringify(embedded),'""');
const start=worker.indexOf("if(url.pathname==='/api/visual-index')");
const end=worker.indexOf("if(url.pathname==='/api/catalog')",start);
if(start<0||end<0)throw new Error('Visual index route not found');
worker=worker.slice(0,start)+"if(url.pathname==='/api/visual-index'){const assetUrl=new URL('/visual-index.json',url);const asset=await env.ASSETS.fetch(new Request(assetUrl));return new Response(asset.body,{status:asset.status,headers:{'Content-Type':'application/json; charset=utf-8','Cache-Control':'public,max-age=3600','X-Content-Type-Options':'nosniff'}})}"+worker.slice(end);
fs.rmSync('pages-dist',{recursive:true,force:true});fs.mkdirSync('pages-dist',{recursive:true});
fs.writeFileSync('pages-dist/_worker.js',worker);
fs.writeFileSync('pages-dist/visual-index.json',gunzipSync(fs.readFileSync('data/visual-index.json.gz')));
fs.writeFileSync('pages-dist/_routes.json',JSON.stringify({version:1,include:['/*'],exclude:['/visual-index.json']}));
console.log('Cloudflare Pages build ready. Worker compressed bytes: '+gzipSync(worker).length);
